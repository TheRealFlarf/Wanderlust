EntityJSEvents.attributes(event => {
    event.modify('minecraft:player', attribute => {
        attribute.add('combat_roll:count', 0)
    })
    event.modify('minecraft:skeleton', attribute => {
        attribute.add('minecraft:generic.max_health', 12)
    })
})

